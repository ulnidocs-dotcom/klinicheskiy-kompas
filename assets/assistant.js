// Ассистент с частыми вопросами в чате пациента (спек 2026-10-22 §C). Чистые функции, без DOM и стора.
// Порядок проверок: 1) кризис — без FAQ, экран помощи и SOS; 2) неотложное состояние — 112 и сообщение врачу;
// 3) беременность — ответ из инструкции и вопрос врачу; 4) изменение лечения или сочетание с другими препаратами —
// «Не меняйте схему сами» и вопрос врачу; 5) ответ из базы KK.data.faq с источником; 6) не нашёл — вопрос врачу.
(function (g) {
  const KK = g.KK = g.KK || {};

  const TEXT = {
    label: 'Ассистент, не врач. Отвечает на частые вопросы по проверенным материалам.',
    hello: 'Здравствуйте. Выберите тему или напишите вопрос своими словами. Если ответа нет в материалах, я передам вопрос врачу.',
    crisis: 'Вы не одни, и хорошо, что вы об этом написали. Сейчас откроется экран помощи: там телефон 112 и линии поддержки, там же видно, получил ли врач сигнал.',
    emergency: 'Это может быть опасно. Если сейчас тяжело дышать, болит в груди, отекает лицо или горло — звоните 112. Я передал сообщение врачу.',
    treatment: 'Не меняйте схему сами. Передал вопрос врачу, он ответит в рабочее время.',
    extraDose: 'Если после этого стало плохо — звоните 112.',
    pregnancy: 'Не прекращайте и не меняйте лечение сами. Передал вопрос врачу, он свяжется с вами в рабочее время.',
    unknown: 'Не нашёл ответа в проверенных материалах. Передал вопрос врачу, он ответит в рабочее время. Если опасно сейчас — звоните 112.',
    forwarded: 'Передал вопрос врачу, он ответит в рабочее время.',
    notSent: 'Вопрос врачу пока не передан: не получилось отправить. Нажмите «Спросить врача» ещё раз.',
    pending: 'Вопрос ждёт отправки и уйдёт врачу, когда появится связь.',
    notHelped: 'Не помогло — спросить врача',
  };

  // Короткие слова и служебные слова не участвуют в подборе ответа из базы.
  const STOP = new Set(['как', 'что', 'мне', 'меня', 'мой', 'моя', 'мои', 'можно', 'ли', 'это', 'если', 'или', 'для', 'при', 'у', 'я', 'и', 'в', 'во',
    'на', 'с', 'со', 'не', 'а', 'но', 'по', 'же', 'бы', 'то', 'да', 'так', 'все', 'уже', 'еще', 'очень', 'о', 'об', 'от', 'до', 'из', 'за', 'к',
    'ко', 'он', 'она', 'они', 'ним', 'нем', 'его', 'ее', 'вы', 'вас', 'вам', 'ты', 'есть', 'был', 'была', 'было', 'будет', 'нужно', 'надо', 'могу',
    'хочу', 'какие', 'какой', 'какая', 'где', 'чем', 'чего', 'этом', 'этот', 'эта', 'тоже', 'просто', 'сейчас', 'сегодня', 'день', 'делать', 'стоит']);

  function normalize(text) {
    return String(text == null ? '' : text).toLowerCase().replace(/ё/g, 'е')
      .replace(/[^a-zа-я0-9\s]+/g, ' ').replace(/\s+/g, ' ').trim();
  }
  const stem = (w) => (w.length >= 4 ? w.slice(0, 5) : w);
  function stems(text) {
    return normalize(text).split(' ').filter((w) => w && !STOP.has(w)).map(stem);
  }

  // ——— Кризис ———
  // Опечатки: «жы/шы», «нехочу», «хочетса», и слова на расстоянии одной правки от ключевых («умиреть», «суецид»).
  const CANON = ['умереть', 'суицид', 'сдохнуть', 'покончить', 'хочется', 'самоубийство', 'повеситься'];
  const REAL_WORDS = new Set(['умерить', 'суицида']); // настоящие слова рядом с ключевыми — не исправляем
  function lev1(a, b) {
    if (Math.abs(a.length - b.length) > 1) return false;
    let i = 0, j = 0, edits = 0;
    while (i < a.length && j < b.length) {
      if (a[i] === b[j]) { i++; j++; continue; }
      if (++edits > 1) return false;
      if (a.length > b.length) i++; else if (a.length < b.length) j++; else { i++; j++; }
    }
    return edits + (a.length - i) + (b.length - j) <= 1;
  }
  function crisisTokens(text) {
    const w = normalize(text).replace(/жы/g, 'жи').replace(/шы/g, 'ши').split(' ').filter(Boolean)
      .flatMap((t) => (/^нехоч/.test(t) ? ['не', t.slice(2)] : [t]))
      .map((t) => {
        if (/^хоч[еи](тс|тьс|ц|тц)[яа]$/.test(t)) return 'хочется';
        if (t.length >= 5 && !REAL_WORDS.has(t) && !CANON.includes(t)) { const c = CANON.find((k) => lev1(t, k)); if (c) return c; }
        return t;
      });
    return w;
  }
  // Фразы (на исправленном тексте; в начале и в конце — пробел).
  const CRISIS = [
    /суицид/, /самоубий/, /самоповрежд/, /покончи(ть|т|л|м)? (с собой|с жизнью)/, /покончу/, /свести сч[её]ты/,
    // Между частями фразы допускаются до двух слов: «не хочу больше жить», «жить уже совсем не хочется».
    /(не хочу|не хочется|нет сил|незачем|не за чем|не могу|не стоит)( [а-я]+){0,2} жить/, /жить( [а-я]+){0,2} (не хочу|не хочется|незачем|не могу|не стоит)/,
    /устал[аи]? (от жизни|жить)/, /(нет|не вижу)( [а-я]+){0,2} смысла( [а-я]+){0,2} (жить|в жизни)/,
    /не (хочу|хочется) (просыпаться|проснуться|существовать)/, /(уснуть|заснуть) и не проснуться/, /(исчезнуть|пропасть) навсегда/,
    /лучше бы я (умер|умерла|не родил)/, /(умереть|умру)( [а-я]+){0,2} (хочу|хочется|было бы лучше)/, /всем (будет|станет) лучше без меня/,
    /смысла жить нет/, /(хочу|хочется|лучше бы|лучше) умереть/, /лучше бы меня не было/, /(уйти|уйду) из жизни/,
    /(убить|убью|убила|убил) себя/, /(режу|резать|порезать|порежу|порезала|порезал) себя/, /(навредить|наврежу|причинить вред|причиню вред) себе/,
    /причинить себе (вред|боль)/, /(выпить|выпью|наглотаться|наглотаюсь|принять|приму) вс[ея] таблетки/, /наглотат|наглотаю/,
    /(спрыгнуть|прыгнуть|выпрыгнуть) (с|из) (крыши|окна|моста|балкона)/, / повеситься | повешусь /,
    /(хочу|хочется|лучше) не быть/, / меня не станет /, /скоро меня не (будет|станет)/, /меня (больше |совсем |уже )?не (будет|станет) $/,
    / прощайте /, /прощай(те)? (все|всем) /, / всем прощай/, /больше не могу|не могу больше/, /сил (больше |уже )?нет|больше нет сил/,
  ];
  // Правила по основам слов: порядок слов не важен.
  function crisisByTokens(w) {
    const at = (re) => w.reduce((a, x, i) => (re.test(x) ? a.concat(i) : a), []);
    const any = (re) => w.some((x) => re.test(x));
    const near = (A, B, k) => A.some((i) => B.some((j) => i !== j && Math.abs(i - j) <= k));
    const after = (A, B, k) => A.some((i) => B.some((j) => j > i && j - i <= k));
    const LIVE = at(/^(жить|живу|жизн)/);
    // «не хочу/не хочется» (в том числе «нехочу»): позиции глагола после «не».
    const NOWANT = at(/^хоч/).filter((i) => w[i - 1] === 'не');
    return any(/^(суицид|самоуби|самоповр|сдох|наглот|поконч)/)
      || (any(/^вен(ы|у|а|ах)?$/) && any(/^(вскр|вскро|резат|реж|пореж|порез)/))
      || (any(/^(себя|себе)$/) && any(/^(убит|убь|убил|убей|реж|резат|пореж|порез|бью$|бить$|била?$|покалеч|задуш|отрав|навред)/))
      || any(/^(режусь|порезалась|порезался)$/)
      || (any(/^(режу|резать|порежу|порезал|порезала)$/) && any(/^(рук|запяст|ног|себ|вен)/))
      || (any(/^смерт/) && any(/^(дума|мысл|хоч|жела|скор|бы$|жду|зов|мечта)/))
      || (any(/^(умереть|умру|помереть)$/) && any(/^(хоч|скор|бы$|чтоб|дума|мечта|лучше|жела|хотел)/))
      || (any(/^(кончу|кончить)$/) && any(/^собой$/))
      || after(at(/^(зачем|незачем|чего)$/), LIVE, 2)
      || near(at(/^смысл/), LIVE, 3)
      || near(NOWANT, LIVE, 3)
      || near(NOWANT, at(/^(проснут|просыпат|существ)/), 3)
      || (any(/^исчезн/) && any(/^(хоч|бы$|лучше|навсегда|мечта)/))
      || (any(/^(выпил|выпью|выпить|приму|принял|принять|наглот|сожр|съем|съела|съел)/)
        && (any(/^(пачк|упаковк|горст|блистер|пузыр)/)
          || (any(/^вс[еюя]$/) && any(/^(таблет|лекарств|колес|пилюл)/) && !any(/^(утрен|вечерн|сегодн|назнач|схем|вовремя|днев)/))))
      || (any(/^(прыгн|спрыгн|выпрыгн|шагн|брошусь|броситься|бросится|кинусь|кинуться|сигану)/) && any(/^(крыш|мост|окн|окош|поезд|машин|рельс|балкон|этаж|электрич)/))
      || (any(/^(выйду|выйти|выпаду)$/) && any(/^(окн|окош)/))
      || (any(/^(лягу|лечь)$/) && any(/^(рельс|поезд)/));
  }
  function isCrisis(text) {
    const w = crisisTokens(text);
    const t = ` ${w.join(' ')} `;
    return CRISIS.some((re) => re.test(t)) || crisisByTokens(w);
  }

  // ——— Неотложное состояние: боль в груди, одышка, обморок, отёк лица или горла, судороги, сыпь с отёком ———
  function isEmergency(text) {
    const n = normalize(text);
    const w = n.split(' ');
    const t = ` ${n} `;
    const any = (re) => w.some((x) => re.test(x));
    return (any(/^груд(и|ь|ина|ине)?$/) && any(/^(бол|давит|давл|жж|жже|колет|сжим|печет)/))
      || (any(/^сердц|^сердце$/) && any(/^(бол|давит|жж|колет|сжим)/))
      || any(/^задыха/) || / (не могу|нечем|трудно|тяжело|тяжко) (дышать|вдохнуть)| не хватает воздуха /.test(t)
      || any(/^(обморок|обморк)/) || /(теря|потеря|потерял)[а-я]* сознани/.test(t)
      || (any(/^(отек|отекл|отека|опух)/) && any(/^(горл|лиц|губ|язык|шея|шеи|гортан|глаз)/))
      || any(/^судорог/) || (any(/^приступ/) && !any(/^(паник|тревог|страх|кашл|голод|злост|гнев)/))
      || (any(/^(сып|крапивн|высып)/) && any(/^(отек|отекл|опух|сильн|везде|всему)/));
  }

  // ——— Беременность и кормление грудью ———
  const PREGNANCY = /беремен|кормлю (ребенка )?грудью|грудью кормлю|кормление грудью|грудное вскармливан|грудном вскармливан|планирую ребенка|зачати/;
  const isPregnancy = (text) => PREGNANCY.test(normalize(text));

  // ——— Изменение лечения: действие со схемой рядом со словом о лекарстве; алкоголь и другие препараты — отдельно ———
  const CHANGE_ACTION = new RegExp(['удво', 'двойн', 'дважды', '(две|три|четыре|2|3|4) таблетк', 'две сразу', 'лишн', 'случайно', 'еще одну таблетку',
    'увелич', 'уменьш', 'снизить', 'снижу', 'повысить', 'повышу', 'половин', 'пол таблетки', 'друг(ую|ая|ой) доз', 'смени', 'поменя', 'замени', 'отмен',
    'брос', 'прекрат', 'перестать', 'перестану', 'перестал', '(не буду|не хочу|не стану) (пить|принимать)', '(^| )не (пью|пила|пил|принимаю|принимала|принимал|выпил|приняла|принял)',
    'пропуст', 'пропущ', 'забыл', 'реже', 'чаще', 'стало лучше', '(один|1|одну) (раз|таблетку) в день', '(только|лишь) (утром|вечером|днем|на ночь|по утрам|по вечерам)'].join('|'));
  const CHANGE_CONTEXT = /таблет|лекарств|препарат|(^| )(доза|дозу|дозы|дозе|дозой|дозировк)|авиандр|маритупирдин|лечени|схем|курс|(^| )пить( |$)|принимать|принять|приня|выпить|прием(?! (у|к) врач)/;
  const EXTRA_DOSE = /дважды|лишн|случайно|двойн|(две|три|четыре|2|3|4) таблетк/;
  const ALCOHOL = /алкогол|спиртн|спиртосодерж|выпивк|выпивш|похмел|запой|(^| )(вино|вина|вином|пиво|пива|пивом|водка|водки|водку|коньяк|коньяка|шампанск)/;
  const COMBO = /антидепрес|снотворн|успокоительн|сертралин|флуоксетин|пароксетин|эсциталопрам|циталопрам|флувоксамин|венлафаксин|дулоксетин|амитриптилин|миртазапин|трамадол|триптан|(^| )лити[йяе]|зверобо|феназепам|алпразолам|диазепам|бензодиазепин|нейролептик|кветиапин|галоперидол|супрастин|димедрол|фенобарбитал|корвалол|валокордин/;
  function isTreatmentChange(text) {
    const t = normalize(text);
    if (ALCOHOL.test(t)) return 'alcohol';
    if (COMBO.test(t)) return 'combination';
    if (!(CHANGE_ACTION.test(t) && CHANGE_CONTEXT.test(t))) return null;
    return EXTRA_DOSE.test(t) && /выпил|приня|съел/.test(t) ? 'extra_dose' : 'change';
  }

  // ——— Ответ из базы ———
  const base = (ctx) => (ctx && ctx.faq) || (KK.data && KK.data.faq ? KK.data.faq.entries : []);
  const cache = new WeakMap();
  function keyInfo(e) {
    if (!cache.has(e)) {
      const phrases = e.keywords.map(stems).filter((p) => p.length);
      cache.set(e, { all: new Set(phrases.flat()), phrases });
    }
    return cache.get(e);
  }
  // Счёт статьи: число основ вопроса среди основ её ключевых слов; при равенстве побеждает более точная статья —
  // больше ключевых фраз, целиком вошедших в вопрос, затем больше доля совпавших основ.
  // Порог: две основы, или одна — если в вопросе всего одна-две значимые основы («побочка», «плохо сплю»).
  function match(text, ctx) {
    const q = [...new Set(stems(text))];
    if (!q.length) return null;
    const qs = new Set(q);
    let best = null, bs = [0, 0, 0];
    for (const e of base(ctx)) {
      const k = keyInfo(e);
      const s = q.filter((x) => k.all.has(x)).length;
      if (!s) continue;
      const sc = [s, k.phrases.filter((p) => p.every((x) => qs.has(x))).length, s / k.all.size];
      if (sc[0] > bs[0] || (sc[0] === bs[0] && (sc[1] > bs[1] || (sc[1] === bs[1] && sc[2] > bs[2])))) { best = e; bs = sc; }
    }
    return bs[0] >= 2 || (bs[0] >= 1 && q.length <= 2) ? best : null;
  }

  function byId(id, ctx) { return base(ctx).find((e) => e.id === id) || null; }
  function topicEntries(topic, ctx) { return base(ctx).filter((e) => e.topic === topic); }
  const sourceText = (e) => (e && e.source ? e.source.title : '');
  const withEntry = (kind, entry, reply) => (entry ? { kind, entry, reply, source: sourceText(entry), forward: true } : { kind, reply, forward: true });

  function answer(text, ctx) {
    if (isCrisis(text)) return { kind: 'crisis', reply: TEXT.crisis, forward: false };
    if (isEmergency(text)) return { kind: 'emergency', reply: TEXT.emergency, forward: true };
    if (isPregnancy(text)) {
      const entry = byId('pregnancy', ctx);
      return withEntry('pregnancy', entry, entry ? `${entry.a} ${TEXT.pregnancy}` : TEXT.pregnancy);
    }
    const change = isTreatmentChange(text);
    if (change) {
      const entry = change === 'alcohol' ? byId('alcohol', ctx) : change === 'combination' ? byId('combination', ctx) : null;
      const reply = [TEXT.treatment, change === 'extra_dose' ? TEXT.extraDose : '', entry ? entry.a : ''].filter(Boolean).join(' ');
      return withEntry('treatment_change', entry, reply);
    }
    const entry = match(text, ctx);
    if (entry) return { kind: 'faq', entry, reply: entry.a, source: sourceText(entry), forward: false };
    return { kind: 'unknown', reply: TEXT.unknown, forward: true };
  }
  // Ответ на выбранный вопрос из списка темы (кнопкой) — без подбора по словам.
  function answerEntry(entry) {
    return { kind: 'faq', entry, reply: entry.a, source: sourceText(entry), forward: false };
  }
  // Ответ, если передать вопрос врачу не получилось: без «Передал…», с подсказкой отправить ещё раз.
  function unsent(reply) {
    const rest = String(reply || '').replace(/ ?(Я передал сообщение врачу|Передал вопрос врачу)[^.]*\./g, '').trim();
    return `${rest} ${TEXT.notSent}`.trim();
  }
  // Полезная нагрузка события 'assistant' (переписка с ассистентом видна врачу в карточке).
  // extra.ref — метка, по которой страница находит переданное врачу сообщение этой реплики.
  function turn(question, r, extra) {
    return Object.assign({ q: String(question || '').slice(0, 500), kind: r.kind, entryId: r.entry ? r.entry.id : null,
      reply: String(r.reply || '').slice(0, 1000) }, extra || {});
  }

  KK.assistant = { TEXT, normalize, stems, isCrisis, isEmergency, isPregnancy, isTreatmentChange, match, answer, answerEntry, unsent, byId, topicEntries, sourceText, turn };
})(typeof window !== 'undefined' ? window : globalThis);
